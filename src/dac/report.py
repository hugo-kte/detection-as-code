"""Write the evaluation artefacts: metrics.json, REPORT.md, detection_matrix.csv and figures."""

from __future__ import annotations

import csv
import json
from datetime import date
from pathlib import Path
from typing import Any

from . import plots
from .convert import ConversionReport
from .datasets import COMMIT, REPO
from .evaluate import EvaluationResult


def short(key: str) -> str:
    """``windows/credential_access/host/x.zip`` -> ``credential_access/x``."""
    parts = key.split("/")
    return f"{parts[1]}/{Path(parts[-1]).stem}" if len(parts) >= 4 else key


def write_matrix(result: EvaluationResult, path: Path) -> Path:
    matrix = result.matrix()
    recordings = sorted(o.recording.key for o in result.outcomes)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["rule", *[short(r) for r in recordings]])
        for slug in sorted(matrix):
            writer.writerow([slug, *[matrix[slug].get(r, 0) for r in recordings]])
    return path


def write_figures(
    result: EvaluationResult, metrics: dict[str, Any], out: Path, first: dict[str, Any] | None
) -> list[Path]:
    figures = out / "figures"
    paths = [
        plots.detection_by_tactic(metrics, figures / "detection_by_tactic.png"),
        plots.per_technique(metrics, figures / "detection_by_technique.png"),
        plots.rule_matrix(
            {lr.path.stem: lr.path.parent.name for lr in result.rules},
            [(f.rule, f.recording, f.expected) for f in result.firings],
            {o.recording.key: o.recording.tactic for o in result.outcomes},
            figures / "rule_matrix.png",
        ),
    ]
    if first:
        paths.append(plots.alerts_before_after(first, metrics, figures / "tuning_before_after.png"))
    return paths


def _pct(x: float) -> str:
    return f"{x:.1%}"


def write_report(
    result: EvaluationResult,
    metrics: dict[str, Any],
    path: Path,
    first: dict[str, Any] | None = None,
    conversion: ConversionReport | None = None,
) -> Path:
    det, alerts, sigs = metrics["detection"], metrics["alerts"], metrics["off_target_signatures"]
    rec = metrics["recordings"]
    lines = [
        "# Evaluation report",
        "",
        f"Generated by `dac evaluate` on {date.today().isoformat()}. Data: [{REPO}]"
        f"(https://github.com/{REPO}) at commit `{COMMIT[:10]}`: {rec['total']} Windows host "
        f"recordings ({rec['events']:,} events in the {rec['scored']} scored ones; "
        f"{len(rec['duplicates_excluded'])} byte-identical duplicate excluded; "
        f"{rec['unlabelled']} without an ATT&CK label). {metrics['rules']} Sigma rules.",
        "",
        "## Headline",
        "",
        "| | |",
        "|---|---|",
        f"| In-scope recordings detected | **{det['detected']} / {det['in_scope']} "
        f"({_pct(det['detection_rate'])})** |",
        f"| Misses, telemetry present but no rule matched | {det['missed_no_rule_match']} |",
        f"| Misses, required telemetry absent | {det['missed_telemetry_absent']} |",
        f"| Alerts | {alerts['total']}: {alerts['expected']} on the labelled technique, "
        f"{alerts['off_target_attack']} off-target attack activity, "
        f"{alerts['false_positive']} false positives, {alerts['unreviewed']} unreviewed |",
        f"| Off-target signatures | {sigs['total']} ({sigs['attack']} attack, "
        f"{sigs['benign']} benign, {sigs['unreviewed']} unreviewed) |",
        "",
    ]
    if first:
        fd, fa = first["detection"], first["alerts"]
        lines += [
            "## First pass vs. after tuning",
            "",
            "The first pass is the rule set as written, before looking at any result. Tuning fixed "
            "rule bugs and added benign-noise filters (see "
            "`reviews/tuning_log.yaml`; the exact rule diff is in "
            "`reports/first_pass/rules.diff`).",
            "",
            "| | First pass | After tuning |",
            "|---|---:|---:|",
            f"| Recordings detected | {fd['detected']} / {fd['in_scope']} "
            f"({_pct(fd['detection_rate'])}) | {det['detected']} / {det['in_scope']} "
            f"({_pct(det['detection_rate'])}) |",
            f"| Alerts | {fa['total']} | {alerts['total']} |",
            f"| On the labelled technique | {fa['expected']} | {alerts['expected']} |",
            f"| Off-target attack activity | {fa['off_target_attack']} | "
            f"{alerts['off_target_attack']} |",
            f"| False positives | {fa['false_positive']} ({_pct(fa['false_positive_share'])}) | "
            f"{alerts['false_positive']} ({_pct(alerts['false_positive_share'])}) |",
            "",
            "Five first-pass detections were right for the wrong reason: the admin-share rule "
            "matched `IPC$` because `C$` is a substring of it. The after-tuning false-positive "
            "count is in-sample (the filters were written from these recordings) and is not an "
            "estimate of the false-positive rate elsewhere.",
            "",
        ]
    lines += [
        "## Detection by tactic",
        "",
        "| Tactic | Detected | In scope | Rate |",
        "|---|---:|---:|---:|",
    ]
    for tactic, v in metrics["per_tactic"].items():
        lines.append(
            f"| {tactic} | {v['detected']} | {v['in_scope']} | {_pct(v['detection_rate'])} |"
        )
    lines += [
        "",
        "## Detection by technique",
        "",
        "| Technique | Name | Detected | Recordings |",
        "|---|---|---:|---:|",
    ]
    for row in metrics["per_technique"]:
        lines.append(
            f"| {row['technique']} | {row['name']} | {row['detected']} | {row['recordings']} |"
        )

    lines += ["", "## Missed recordings", "", "| Recording | Label | Reason |", "|---|---|---|"]
    for o in sorted(result.outcomes, key=lambda o: o.recording.key):
        if o.in_scope and not o.detected:
            label = ", ".join(sorted(o.recording.techniques))
            lines.append(f"| {short(o.recording.key)} | {label} | {o.miss_reason} |")

    lines += [
        "",
        "## Off-target alert signatures",
        "",
        "| Rule | Signature | Alerts | Recordings | Verdict | Rationale |",
        "|---|---|---:|---:|---|---|",
    ]
    for g in result.off_target:
        rationale = g.verdict.rationale if g.verdict else ""
        signature = g.signature.replace("|", "\\|")
        lines.append(
            f"| {g.rule} | `{signature}` | {g.alerts} | {len(g.recordings)} | "
            f"{g.status} | {rationale} |"
        )
    if result.stale_verdicts:
        lines += [
            "",
            f"{len(result.stale_verdicts)} reviewed signatures no longer fire (removed by "
            "the fixes and filters); their verdicts stay in `reviews/off_target.yaml`.",
        ]

    lines += [
        "",
        "## Rules",
        "",
        "| Rule | Level | Techniques | Alerts | Recordings | Labelled detections | FP alerts |",
        "|---|---|---|---:|---:|---:|---:|",
    ]
    for slug, row in sorted(metrics["per_rule"].items()):
        lines.append(
            f"| {slug} | {row['level']} | {', '.join(row['techniques'])} | {row['alerts']} | "
            f"{row['recordings_fired']} | {row['labelled_recordings_fired']} / "
            f"{row['labelled_recordings']} | {row['false_positive_alerts']} |"
        )
    if metrics["rules_without_validated_detection"]:
        lines += [
            "",
            "Rules with no validated detection on this data: "
            + ", ".join(f"`{s}`" for s in metrics["rules_without_validated_detection"])
            + ".",
        ]
    if metrics["uncovered_techniques"]:
        lines += [
            "",
            "Techniques exercised by recordings but covered by no rule: "
            + ", ".join(
                f"{t['technique']} ({t['recordings']})" for t in metrics["uncovered_techniques"]
            )
            + ".",
        ]
    if conversion:
        lines += [
            "",
            "## Query conversion",
            "",
            "| Target | Converted | Not convertible |",
            "|---|---:|---|",
        ]
        for s in conversion.summary().values():
            missing = ", ".join(f"`{r}`" for r in sorted(s["unsupported"])) or "-"
            label = s["label"].replace("|", "\\|")
            lines.append(f"| {label} | {s['converted']} / {s['total']} | {missing} |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def write_metrics(metrics: dict[str, Any], path: Path, conversion: ConversionReport | None) -> Path:
    payload = {"data": {"repo": REPO, "commit": COMMIT}, **metrics}
    if conversion:
        payload["conversion"] = {
            name: {k: v for k, v in s.items() if k != "label"}
            for name, s in conversion.summary().items()
        }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    return path
